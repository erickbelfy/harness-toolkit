# shellcheck shell=bash
# agentsmd.sh — generate a single root AGENTS.md (the cross-tool standard).
#
# AGENTS.md is plain markdown with NO frontmatter. We flatten:
#   rules    -> prose sections (priority-ordered)
#   commands -> a "## Commands" list
#   mcp      -> a human-readable "## Tooling (MCP)" note
# Requires harness-scope helpers: list_artifacts, target_selected, artifact_id,
# humanize, fm_get, fm_body, emit_write, and $SRC_DIR/$OUT_DIR.

gen_agentsmd() {
  local out_dir; out_dir="$OUT_DIR/$(manifest_target_out "$MANIFEST" agentsmd)"
  local tmp; tmp="$(mktemp)"
  {
    printf '# AGENTS.md\n\n'
    printf '<!-- Generated by harness. Edit canonical sources in harness/, then run `harness build`. -->\n\n'
    printf 'Instructions for AI coding agents working in this repository.\n'

    _agentsmd_rules
    _agentsmd_commands
    _agentsmd_mcp
  } >"$tmp"

  emit_write "$out_dir/AGENTS.md" <"$tmp"
  rm -f "$tmp"
}

# Rules, ordered by ascending priority (default 50), each as a prose section.
_agentsmd_rules() {
  local f pr line
  # Build "priority<TAB>file" then sort numerically, stable.
  local rows; rows="$(
    while IFS= read -r f; do
      target_selected "$f" rules agentsmd || continue
      pr="$(fm_get "$f" priority)"; pr="${pr:-50}"
      printf '%s\t%s\n' "$pr" "$f"
    done < <(list_artifacts rules) | LC_ALL=C sort -n -s -k1,1
  )"
  [ -z "$rows" ] && return 0
  while IFS=$'\t' read -r pr f; do
    [ -z "$f" ] && continue
    printf '\n## %s\n\n' "$(humanize "$(artifact_id "$f" rules)")"
    fm_body "$f" | _strip_blank_edges
  done <<<"$rows"
}

_agentsmd_commands() {
  local f any=0 name desc
  while IFS= read -r f; do
    target_selected "$f" commands agentsmd || continue
    if [ "$any" = 0 ]; then printf '\n## Commands\n\n'; any=1; fi
    name="$(artifact_id "$f" commands)"; desc="$(fm_get "$f" description)"
    printf -- '- **%s**: %s\n' "$name" "$desc"
  done < <(list_artifacts commands)
}

_agentsmd_mcp() {
  local f any=0 name tr desc
  while IFS= read -r f; do
    target_selected "$f" mcp agentsmd || continue
    if [ "$any" = 0 ]; then
      printf '\n## Tooling (MCP)\n\n'
      printf 'These MCP servers are configured for agents that support them:\n\n'; any=1
    fi
    name="$(artifact_id "$f" mcp)"; tr="$(fm_get "$f" transport)"; tr="${tr:-stdio}"
    desc="$(fm_body "$f" | _first_line)"
    printf -- '- **%s** (%s): %s\n' "$name" "$tr" "$desc"
  done < <(list_artifacts mcp)
}

# Trim leading and trailing blank lines from stdin.
_strip_blank_edges() {
  awk 'BEGIN{started=0} { lines[NR]=$0 } END{
    s=1; while(s<=NR && lines[s]=="") s++
    e=NR; while(e>=1 && lines[e]=="") e--
    for(i=s;i<=e;i++) print lines[i]
  }'
}

_first_line() { awk 'NF{print; exit}'; }
