# shellcheck shell=bash
# gastown.sh — generate configuration for Steve Yegge's Gas Town orchestrator.
#
#   agents -> .gastown/roles/<name>.md (persona prompt) + .gastown/roles.json
#   hooks  -> .github/hooks/gastown.json  (Claude event names translated)
#   mcp    -> .mcp.json (shared writer)
#   memory -> .beads/issues.jsonl  OR  .beads/seed.sh   (per beads_mode)
#
# NOTE: Gastown is experimental and its on-disk schema is still moving. These
# outputs are structured, documented interchange artifacts a Gastown user wires
# in; the beads DB itself (Dolt) is never written directly.
# Requires harness-scope helpers.

# Claude -> Gastown hook event name translation. Unmapped events are dropped.
_gastown_event() {
  case "$1" in
    SessionStart)     echo sessionStart ;;
    SessionEnd)       echo sessionEnd ;;
    UserPromptSubmit) echo userPromptSubmitted ;;
    PreToolUse)       echo preToolUse ;;
    *)                echo "" ;;
  esac
}

gen_gastown() {
  local out; out="$OUT_DIR/$(manifest_target_out "$MANIFEST" gastown)"
  _gastown_agents "$out"
  _gastown_hooks "$out"
  write_mcp_json "$out" gastown
  _gastown_memory "$out"
}

# Roles: persona body -> .gastown/roles/<name>.md; index -> .gastown/roles.json.
_gastown_agents() {
  local out="$1" f name desc role model first=1 body=""
  while IFS= read -r f; do
    target_selected "$f" agents gastown || continue
    name="$(artifact_id "$f" agents)"
    desc="$(fm_get "$f" description)"
    role="$(fm_get "$f" gastown_role)"
    model="$(fm_get "$f" model)"
    local skills_json; skills_json="$(fm_get_list "$f" skills | json_arr_from_lines)"
    emit_write "$out/.gastown/roles/$name.md" < <(fm_body "$f"; agent_skills_section "$f")
    [ "$first" = 1 ] && first=0 || body="$body,"
    body="$body
    $(json_str "$name"): {\"preset\": $(json_str "${role:-}"), \"model\": $(json_str "${model:-inherit}"), \"description\": $(json_str "$desc"), \"skills\": ${skills_json}, \"prompt\": $(json_str ".gastown/roles/$name.md")}"
  done < <(list_artifacts agents)
  [ "$first" = 1 ] && return 0
  emit_write "$out/.gastown/roles.json" < <(printf '{\n  "roles": {%s\n  }\n}\n' "$body")
}

# Hooks: translate event names; drop unmapped with a warning. Group by event.
_gastown_hooks() {
  local out="$1" f ev gev cmd rows=""
  while IFS= read -r f; do
    target_selected "$f" hooks gastown || continue
    ev="$(fm_get "$f" event)"; gev="$(_gastown_event "$ev")"
    if [ -z "$gev" ]; then
      warn "SKIP target=gastown hook=$(artifact_id "$f" hooks): event '$ev' has no Gastown mapping"
      continue
    fi
    cmd="$(fm_get "$f" command)"
    rows="$rows$gev	$(json_str "$cmd")
"
  done < <(list_artifacts hooks)

  [ -z "${rows//[$'\n']/}" ] && return 0
  local obj
  obj="$(printf '%s' "$rows" | LC_ALL=C sort -t'	' -k1,1 -s | awk -F'	' '
    NF==0||$1=="" {next}
    { ev=$1; cmd=$2
      if(!(ev in seen)){seen[ev]=1; order[++n]=ev}
      h="{\"command\": " cmd "}"
      cmds[ev]=(ev in cmds ? cmds[ev] ", " : "") h }
    END{ printf "{"
      for(i=1;i<=n;i++){ printf "%s\n    \"%s\": [%s]", (i>1?",":""), order[i], cmds[order[i]] }
      printf "\n  }" }')"
  emit_write "$out/.github/hooks/gastown.json" < <(printf '{\n  "hooks": %s\n}\n' "$obj")
}

# Memory: seed beads from kind:beads artifacts.
_gastown_memory() {
  local out="$1" mode; mode="$(manifest_get "$MANIFEST" targets.gastown beads_mode)"; mode="${mode:-jsonl}"
  local f had=0
  local jsonl="" script="#!/usr/bin/env bash
# Generated by harness — seed the beads tracker. Run once: bash .beads/seed.sh
set -euo pipefail
command -v bd >/dev/null || { echo 'beads (bd) not installed' >&2; exit 1; }
bd init 2>/dev/null || true
"
  while IFS= read -r f; do
    [ "$(fm_get "$f" kind)" = beads ] || continue
    target_selected "$f" memory gastown || continue
    had=1
    while IFS=$'\t' read -r title priority type; do
      [ -z "$title" ] && continue
      priority="${priority:-2}"; type="${type:-task}"
      jsonl="$jsonl{\"title\": $(json_str "$title"), \"type\": $(json_str "$type"), \"priority\": ${priority}, \"status\": \"open\"}
"
      script="$script"$'\n'"bd create $(printf '%q' "$title") -p ${priority} -t ${type}"
    done < <(_beads_parse "$f")
  done < <(list_artifacts memory)
  [ "$had" = 0 ] && return 0

  if [ "$mode" = script ]; then
    emit_write "$out/.beads/seed.sh" < <(printf '%s\n' "$script")
    [ "$HARNESS_DRY_RUN" = 1 ] || chmod +x "$out/.beads/seed.sh" 2>/dev/null || true
  else
    emit_write "$out/.beads/issues.jsonl" < <(printf '%s' "$jsonl")
  fi
}

# _beads_parse <file> — parse the `beads:` list-of-maps into TSV rows:
#   title<TAB>priority<TAB>type   (one per bead)
_beads_parse() {
  fm_raw "$1" | awk '
    function trim(s){ gsub(/^[ \t]+|[ \t]+$/,"",s); return s }
    function unq(s){ s=trim(s); if(s ~ /^".*"$/||s ~ /^'\''.*'\''$/) s=substr(s,2,length(s)-2); return s }
    function flush(){ if(have){ printf "%s\t%s\t%s\n", title, priority, type } have=0; title="";priority="";type="" }
    {
      if (inb) {
        if ($0 ~ /^[ \t]*-[ \t]/) {                 # new list item
          flush(); have=1
          rest=$0; sub(/^[ \t]*-[ \t]*/,"",rest)
          p=index(rest,":"); if(p>0){ k=trim(substr(rest,1,p-1)); v=unq(substr(rest,p+1)); if(k=="title")title=v; else if(k=="priority")priority=v; else if(k=="type")type=v }
          next
        } else if ($0 ~ /^[ \t]+[^ \t-]/ && index($0,":")>0) {   # continuation field
          p=index($0,":"); k=trim(substr($0,1,p-1)); v=unq(substr($0,p+1))
          if(k=="title")title=v; else if(k=="priority")priority=v; else if(k=="type")type=v
          next
        } else { flush(); inb=0 }
      }
      p=index($0,":"); if(p==0) next
      k=trim(substr($0,1,p-1))
      if (k=="beads" && trim(substr($0,p+1))=="") inb=1
    }
    END{ flush() }
  '
}
