# shellcheck shell=bash
# claude.sh — generate Claude Code configuration.
#   rules    -> CLAUDE.md (priority-ordered prose)
#   agents   -> .claude/agents/<name>.md (subagent frontmatter + system prompt)
#   commands -> .claude/commands/<slug>.md (slash-command prompt files)
#   skills   -> .claude/skills/<name>/ (verbatim Agent-Skills tree copy)
#   mcp      -> .mcp.json (mcpServers map; shared writer)
#   hooks    -> .claude/settings.json (added in claude_hooks, see M3)
# Requires harness-scope helpers.

gen_claude() {
  local out; out="$OUT_DIR/$(manifest_target_out "$MANIFEST" claude)"
  _claude_md       "$out"
  _claude_agents   "$out"
  _claude_commands "$out"
  _claude_skills   "$out"
  write_mcp_json   "$out" claude
  claude_hooks     "$out"   # defined in generators/claude.sh (M3 section below)
}

# CLAUDE.md — concat claude-bound rules, priority-ordered.
_claude_md() {
  local out="$1" f pr rows
  rows="$(
    while IFS= read -r f; do
      target_selected "$f" rules claude || continue
      pr="$(fm_get "$f" priority)"; pr="${pr:-50}"
      printf '%s\t%s\n' "$pr" "$f"
    done < <(list_artifacts rules) | LC_ALL=C sort -n -s -k1,1
  )"
  [ -z "$rows" ] && return 0
  local tmp; tmp="$(mktemp)"
  {
    printf '# CLAUDE.md\n\n'
    printf '<!-- Generated by harness. Edit canonical sources in harness/, then run `harness build`. -->\n'
    while IFS=$'\t' read -r pr f; do
      [ -z "$f" ] && continue
      printf '\n## %s\n\n' "$(humanize "$(artifact_id "$f" rules)")"
      fm_body "$f" | awk 'BEGIN{s=0}{l[NR]=$0}END{a=1;while(a<=NR&&l[a]=="")a++;b=NR;while(b>=1&&l[b]=="")b--;for(i=a;i<=b;i++)print l[i]}'
    done <<<"$rows"
  } >"$tmp"
  emit_write "$out/CLAUDE.md" <"$tmp"; rm -f "$tmp"
}

# .claude/agents/<name>.md — subagent definition.
_claude_agents() {
  local out="$1" f name desc tools model tmp
  while IFS= read -r f; do
    target_selected "$f" agents claude || continue
    name="$(artifact_id "$f" agents)"; desc="$(fm_get "$f" description)"
    tools="$(fm_get_list "$f" tools | paste -sd, - | sed 's/,/, /g')"
    skills="$(fm_get_list "$f" skills | paste -sd, - | sed 's/,/, /g')"
    model="$(fm_get "$f" model)"
    tmp="$(mktemp)"
    {
      printf -- '---\n'
      printf 'name: %s\n' "$name"
      printf 'description: %s\n' "$desc"
      [ -n "$tools" ] && printf 'tools: %s\n' "$tools"
      [ -n "$skills" ] && printf 'skills: %s\n' "$skills"
      [ -n "$model" ] && [ "$model" != inherit ] && printf 'model: %s\n' "$model"
      printf -- '---\n\n'
      fm_body "$f"
      agent_skills_section "$f"
    } >"$tmp"
    emit_write "$out/.claude/agents/$name.md" <"$tmp"; rm -f "$tmp"
  done < <(list_artifacts agents)
}

# .claude/commands/<slug>.md — slash command prompt file.
_claude_commands() {
  local out="$1" f name desc tmp
  while IFS= read -r f; do
    target_selected "$f" commands claude || continue
    name="$(artifact_id "$f" commands)"; desc="$(fm_get "$f" description)"
    tmp="$(mktemp)"
    {
      if [ -n "$desc" ]; then printf -- '---\ndescription: %s\n---\n\n' "$desc"; fi
      fm_body "$f"
    } >"$tmp"
    emit_write "$out/.claude/commands/$name.md" <"$tmp"; rm -f "$tmp"
  done < <(list_artifacts commands)
}

# .claude/skills/<name>/ — copy the whole Agent-Skills directory verbatim.
_claude_skills() {
  local out="$1" f name skdir
  while IFS= read -r f; do
    target_selected "$f" skills claude || continue
    skdir="$(dirname "$f")"; name="$(basename "$skdir")"
    emit_copy_tree "$skdir" "$out/.claude/skills/$name"
  done < <(list_artifacts skills)
}

# claude_hooks — emit hooks into .claude/settings.json and copy hook scripts.
# Also emits git-hook shims under .harness/git-hooks/ for hooks with `git_hook`.
claude_hooks() {
  local out="$1" f rows="" event matcher type cmd timeout
  while IFS= read -r f; do
    target_selected "$f" hooks claude || continue
    event="$(fm_get "$f" event)";   [ -z "$event" ] && { warn "$f: hook missing event; skipped"; continue; }
    matcher="$(fm_get "$f" matcher)"
    type="$(fm_get "$f" type)";     type="${type:-command}"
    cmd="$(fm_get "$f" command)"
    timeout="$(fm_get "$f" timeout)"
    # Pre-quote JSON-string fields so awk can emit them verbatim (tab-safe).
    rows="$rows$event	$( [ -n "$matcher" ] && json_str "$matcher" )	$(json_str "$type")	$(json_str "$cmd")	$timeout
"
  done < <(list_artifacts hooks)

  # Copy hook scripts (referenced relatively) into the target's .harness/hooks/.
  if [ -d "$SRC_DIR/hooks/scripts" ]; then
    emit_copy_tree "$SRC_DIR/hooks/scripts" "$out/.harness/hooks"
    # ensure scripts are executable in the destination
    [ "$HARNESS_DRY_RUN" = 1 ] || find "$out/.harness/hooks" -name '*.sh' -exec chmod +x {} + 2>/dev/null || true
  fi
  _claude_git_hooks "$out"

  [ -z "${rows//[$'\n']/}" ] && return 0

  local hooks_obj
  hooks_obj="$(printf '%s' "$rows" | _hooks_json)"
  _write_settings_hooks "$out" "$hooks_obj"
}

# _hooks_json — stdin TSV "event<TAB>mtoken<TAB>tytoken<TAB>cmdtoken<TAB>timeout"
# -> the value of the "hooks" key: { "<event>": [ {matcher,hooks:[...]} ] }.
_hooks_json() {
  LC_ALL=C sort -t'	' -k1,1 -k2,2 -s | awk -F'	' '
    NF==0 || $1=="" { next }
    {
      ev=$1; m=$2; ty=$3; cmd=$4; to=$5
      if (!(ev in evseen)) { evseen[ev]=1; evorder[++ne]=ev }
      key=ev SUBSEP m
      if (!(key in mseen)) { mseen[key]=1; mcount[ev]++; morder[ev,mcount[ev]]=m }
      h="{\"type\": " ty ", \"command\": " cmd
      if (to!="") h=h ", \"timeout\": " to+0
      h=h "}"
      handlers[key]=(key in handlers ? handlers[key] ", " : "") h
    }
    END{
      printf "{"
      for (i=1;i<=ne;i++){
        ev=evorder[i]
        printf "%s\n    \"%s\": [", (i>1?",":""), ev
        for (j=1;j<=mcount[ev];j++){
          m=morder[ev,j]; key=ev SUBSEP m
          printf "%s\n      {", (j>1?",":"")
          if (m!="") printf "\"matcher\": %s, ", m
          printf "\"hooks\": [%s]}", handlers[key]
        }
        printf "\n    ]"
      }
      printf "\n  }"
    }
  '
}

# _write_settings_hooks <out_dir> <hooks_json_value>
# Harness-owned when the file is absent or exactly our clean output; otherwise
# jq-merge the .hooks key, or (no jq) write a fragment and warn.
_write_settings_hooks() {
  local out="$1" hooks="$2" path full frag
  path="$out/.claude/settings.json"
  full="$(printf '{\n  "hooks": %s\n}\n' "$hooks")"

  if [ ! -f "$path" ] || printf '%s\n' "$full" | cmp -s - "$path"; then
    emit_write "$path" < <(printf '%s\n' "$full")
    return 0
  fi
  if has_cmd jq; then
    local merged
    if merged="$(jq --argjson h "$hooks" '.hooks = $h' "$path" 2>/dev/null)"; then
      emit_write "$path" < <(printf '%s\n' "$merged")
    else
      warn "jq merge failed for $path; left unchanged"
    fi
  else
    frag="$out/.claude/settings.harness.json"
    emit_write "$frag" < <(printf '%s\n' "$full")
    warn "$path exists with non-harness content and jq is unavailable; wrote $frag — merge the .hooks key manually"
  fi
}

# _claude_git_hooks <out_dir> — for hooks declaring `git_hook:`, emit a shim
# under .harness/git-hooks/<name> that runs the referenced command(s). Install
# via `git config core.hooksPath .harness/git-hooks`. Each shim's full content
# is built in one pass so writes stay idempotent.
_claude_git_hooks() {
  local out="$1" f gh cmd line
  declare -A body=()
  local names=""
  while IFS= read -r f; do
    target_selected "$f" hooks claude || continue
    gh="$(fm_get "$f" git_hook)"; [ -z "$gh" ] && continue
    cmd="$(fm_get "$f" command)"
    # Resolve ${CLAUDE_PROJECT_DIR} to the repo root at git-hook runtime.
    line="$(printf '%s' "$cmd" | sed 's#${CLAUDE_PROJECT_DIR}#"$(git rev-parse --show-toplevel)"#g')"
    case " $names " in *" $gh "*) ;; *) names="$names $gh" ;; esac
    body[$gh]="${body[$gh]:-}${line}
"
  done < <(list_artifacts hooks)

  local n
  for n in $names; do
    emit_write "$out/.harness/git-hooks/$n" < <(
      printf '#!/usr/bin/env bash\n'
      printf '# Generated by harness. Install: git config core.hooksPath .harness/git-hooks\n'
      printf 'set -e\n'
      printf '%s' "${body[$n]}"
    )
    [ "$HARNESS_DRY_RUN" = 1 ] || chmod +x "$out/.harness/git-hooks/$n" 2>/dev/null || true
  done
}
